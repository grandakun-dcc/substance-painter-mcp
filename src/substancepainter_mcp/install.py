"""Install only this fork's plugin; preserve edited managed files and other plugins."""

import hashlib
import json
import shutil
import sys
import time
from pathlib import Path

from . import __version__
from .common import atomic_write, dumps, home


def fingerprint(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def install(painter_python=None, replace_edited=False):
    root = home()
    record_path = root / "installation.json"
    previous = json.loads(record_path.read_text("utf-8")) if record_path.exists() else {}
    python_root = Path(painter_python or previous.get("painter_python") or root / "python").resolve()
    modules = root / "modules"
    package = Path(__file__).parent
    targets = {}
    for source in package.rglob("*"):
        if source.is_file() and source.suffix in (".py", ".json", ".txt", ".md") and "__pycache__" not in source.parts:
            targets[modules / "substancepainter_mcp" / source.relative_to(package)] = source.read_text("utf-8")
    license_source = package / "licenses"
    if not license_source.is_dir():
        license_source = package.parent.parent / "licenses"
    for source in license_source.glob("*.txt"):
        targets[modules / "substancepainter_mcp/licenses" / source.name] = source.read_text("utf-8")
    notice = package / "THIRD_PARTY_NOTICES.md"
    if not notice.exists():
        notice = package.parent.parent / "THIRD_PARTY_NOTICES.md"
    if notice.exists():
        targets[modules / "substancepainter_mcp/THIRD_PARTY_NOTICES.md"] = notice.read_text("utf-8")
    startup = python_root / "startup/substancepainter_startup.py"
    targets[startup] = (
        '"""SubstancePainter-MCP startup (generated by its installer)."""\n'
        "import sys\n"
        "sys.dont_write_bytecode = True\n"
        f"sys.path.insert(0, {str(modules)!r})\n"
        "from substancepainter_mcp.plugin import start_plugin, close_plugin\n"
    )
    targets[python_root / "startup/substancepainter_window.py"] = (
        '"""Dedicated worker window policy, managed by SubstancePainter-MCP."""\n'
        "from substancepainter_mcp.worker_window import start_plugin, close_plugin\n"
    )
    old_hashes = previous.get("files", {})
    changed = [str(path) for path, text in targets.items() if path.exists()
               and fingerprint(path) != hashlib.sha256(text.encode("utf-8")).hexdigest()
               and (str(path) not in old_hashes or fingerprint(path) != old_hashes[str(path)])]
    if changed and not replace_edited:
        return {"installed": False, "edited_files": changed,
                "hint": "Review edits; --replace-edited backs them up before replacement."}
    backups = []
    for name in changed:
        path = Path(name)
        backup = root / "backups" / str(time.time_ns()) / path.name
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, backup)
        backups.append(str(backup))
    for path, text in targets.items():
        atomic_write(path, text)
    record = {"version": __version__, "python": sys.executable,
              "painter_python": str(python_root),
              "files": {str(path): fingerprint(path) for path in targets}}
    atomic_write(record_path, dumps(record))
    return {"installed": True, "version": __version__, "state": str(root),
            "painter_python": str(python_root), "backups": backups,
            "hint": "Start a new worker with SUBSTANCE_PAINTER_PLUGINS_PATH pointing to painter_python."}


def uninstall():
    record_path = home() / "installation.json"
    if not record_path.exists():
        return {"removed": [], "preserved": []}
    record = json.loads(record_path.read_text("utf-8"))
    removed, preserved = [], []
    for name, expected in record["files"].items():
        path = Path(name)
        if not path.exists():
            continue
        if path.is_symlink() or fingerprint(path) != expected:
            preserved.append(name)
        else:
            path.unlink()
            removed.append(name)
    if not preserved:
        record_path.unlink()
    return {"removed": removed, "preserved": preserved}
